// PF5 check (03 §20.4, 01 §6.6): gzip size of the initial JS (entry + its static imports and modulepreloads) and
// CSS, the top contributors by package (from source maps), and "no desktop host code in the first chunk" (16.1).
// The desktop host and upstream's IPC client are dynamic chunks that the build also preloads (`data-own-desktop`,
// PF1, vite.config.ts): the web fallback fetches them but never runs them, so they are measured apart
// (desktopPreload) and must hold nothing but desktop code; the budget and the leak check cover the rest.
// Run after `bun run build`: `bun run size` (add `--json` for a machine-readable line).
import { gzipSync } from "bun"
import path from "node:path"

const DIST = path.join(import.meta.dir, "..", "dist")
const BUDGET_JS = 400 * 1024
const TRACK_CSS = 60 * 1024
const BASE64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

const html = await Bun.file(path.join(DIST, "index.html")).text()
const scripts = [...html.matchAll(/<script[^>]+src="\/([^"]+)"/g)].map((match) => match[1]!)
const links = [...html.matchAll(/<link[^>]+rel="modulepreload"[^>]*>/g)].map((match) => match[0])
const href = (tag: string) => /href="\/([^"]+)"/.exec(tag)?.[1]
const isDesktopPreload = (tag: string) => /\sdata-own-desktop\b/.test(tag)
const preloads = links.filter((tag) => !isDesktopPreload(tag)).flatMap((tag) => href(tag) ?? [])
const styles = [...html.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="\/([^"]+)"/g)].map((match) => match[1]!)
const initial = await staticImports([...new Set([...scripts, ...preloads])])
const desktopOnly = links
  .filter(isDesktopPreload)
  .flatMap((tag) => href(tag) ?? [])
  .filter((file) => !initial.includes(file))
const desktopJs = await Promise.all(desktopOnly.map((file) => measure(file)))
const desktopPreloadGzip = desktopJs.reduce((sum, item) => sum + item.gzip, 0)
// A desktop preload carrying anything but desktop code would ship web code that the budget does not see.
const desktopForeign = (await byPackage(desktopOnly))
  .filter((item) => !isDesktopCode(item.name))
  .map((item) => item.name)

const js = await Promise.all(initial.map((file) => measure(file)))
const css = await Promise.all(styles.map((file) => measure(file)))
const totalJs = js.reduce((sum, item) => sum + item.gzip, 0)
const totalCss = css.reduce((sum, item) => sum + item.gzip, 0)
const contributors = await byPackage(initial)
const desktopLeak = contributors.some((item) => item.name.includes("own-web/src/host/desktop"))

if (process.argv.includes("--json")) {
  console.log(
    JSON.stringify({
      initialJsGzip: totalJs,
      cssGzip: totalCss,
      files: js,
      desktopLeak,
      desktopPreloadGzip,
      desktopPreloads: desktopJs,
      desktopForeign,
    }),
  )
} else {
  for (const item of js)
    console.log(`js   ${kb(item.gzip).padStart(9)} gz  ${kb(item.raw).padStart(9)} raw  ${item.file}`)
  for (const item of css)
    console.log(`css  ${kb(item.gzip).padStart(9)} gz  ${kb(item.raw).padStart(9)} raw  ${item.file}`)
  console.log(
    `\ninitial JS gzip ${kb(totalJs)} (budget ${kb(BUDGET_JS)}), CSS gzip ${kb(totalCss)} (tracked ${kb(TRACK_CSS)})`,
  )
  console.log("\nlargest contributors to the initial JS (generated bytes before gzip):")
  for (const item of contributors.slice(0, 15)) console.log(`  ${kb(item.bytes).padStart(9)}  ${item.name}`)
  console.log(`\ndesktop host code in the initial JS: ${desktopLeak ? "YES (fail)" : "no"}`)
  for (const item of desktopJs)
    console.log(`desktop preload ${kb(item.gzip).padStart(9)} gz  ${kb(item.raw).padStart(9)} raw  ${item.file}`)
  if (desktopForeign.length)
    console.log(`non-desktop code in the desktop preloads (fail): ${desktopForeign.join(", ")}`)
}
if (totalJs > BUDGET_JS || desktopLeak || desktopForeign.length) process.exit(1)

function isDesktopCode(name: string) {
  return name === "own-web/src/host/desktop" || name === "packages/desktop" || name === "packages/own-desktop"
}

async function measure(file: string) {
  const bytes = new Uint8Array(await Bun.file(path.join(DIST, file)).arrayBuffer())
  return { file, raw: bytes.length, gzip: gzipSync(bytes, { level: 9 }).length }
}

/** Follows static `import … from "./x.js"` edges between emitted chunks (dynamic imports stay out). */
async function staticImports(entries: string[]) {
  const seen = new Set(entries)
  const queue = [...entries]
  while (queue.length) {
    const file = queue.pop()!
    const code = await Bun.file(path.join(DIST, file)).text()
    for (const match of code.matchAll(/(?:^|[;\n}])\s*import\s*(?:[^"'()]*?from\s*)?["'](\.{1,2}\/[^"']+)["']/g)) {
      const target = path.posix.join(path.posix.dirname(file), match[1]!)
      if (seen.has(target)) continue
      seen.add(target)
      queue.push(target)
    }
  }
  return [...seen]
}

/** Generated bytes per package or own-web directory, attributed through the chunks' source-map segments. */
async function byPackage(files: string[]) {
  const totals = new Map<string, number>()
  for (const file of files) {
    const map = Bun.file(path.join(DIST, `${file}.map`))
    if (!(await map.exists())) continue
    const parsed = (await map.json()) as { sources: string[]; mappings: string }
    const lines = (await Bun.file(path.join(DIST, file)).text()).split("\n")
    const base = path.dirname(path.join(DIST, file))
    const names = parsed.sources.map((source) => packageOf(path.resolve(base, source)))
    const cursor = { source: 0 }
    parsed.mappings.split(";").forEach((line, row) => {
      const segments = decodeLine(line, cursor)
      segments.forEach((segment, index) => {
        if (segment.source === undefined) return
        const end = segments[index + 1]?.column ?? lines[row]?.length ?? segment.column
        const name = names[segment.source] ?? "?"
        totals.set(name, (totals.get(name) ?? 0) + Math.max(0, end - segment.column))
      })
    })
  }
  return [...totals].map(([name, bytes]) => ({ name, bytes })).toSorted((a, b) => b.bytes - a.bytes)
}

/** One generated line of source-map VLQ: the column resets per line, the source index runs across lines. */
function decodeLine(line: string, cursor: { source: number }) {
  const out: { column: number; source?: number }[] = []
  let column = 0
  for (const segment of line.split(",")) {
    if (!segment) continue
    const values = vlq(segment)
    column += values[0] ?? 0
    if (values.length >= 4) cursor.source += values[1] ?? 0
    out.push({ column, source: values.length >= 4 ? cursor.source : undefined })
  }
  return out
}

function vlq(segment: string) {
  const values: number[] = []
  let value = 0
  let shift = 0
  for (const char of segment) {
    const digit = BASE64.indexOf(char)
    value += (digit & 31) << shift
    if (digit & 32) {
      shift += 5
      continue
    }
    values.push(value & 1 ? -(value >>> 1) : value >>> 1)
    value = 0
    shift = 0
  }
  return values
}

function packageOf(source: string) {
  const normalized = source.replaceAll("\\", "/")
  const modules = normalized.lastIndexOf("node_modules/")
  if (modules >= 0) {
    const rest = normalized.slice(modules + "node_modules/".length).split("/")
    return rest[0]!.startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0]!
  }
  const packages = normalized.match(/packages\/([^/]+)\/(src\/[^/]+)?/)
  // The desktop host by itself: grouped as `own-web/src/host`, the leak check below could never see it.
  if (/packages\/own-web\/src\/host\/desktop\.[jt]sx?$/.test(normalized)) return "own-web/src/host/desktop"
  if (packages?.[1] === "own-web") return `own-web/${packages[2] ?? ""}`.replace(/\/$/, "")
  return packages ? `packages/${packages[1]}` : normalized
}

function kb(bytes: number) {
  return `${(bytes / 1024).toFixed(1)} KB`
}
