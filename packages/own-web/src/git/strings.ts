const catalogs: Record<Locale, Partial<Record<GitKey, string>>> = { ko: gitKo, en: gitEn }

export function gitText(locale: Locale, key: GitKey, params?: I18nParams) {
  const template = catalogs[locale][key] ?? gitKo[key]
  const filled = params
    ? template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name]
        return value === undefined ? match : String(value)
      })
    : template
  return locale === "ko" ? applyJosa(filled) : filled
}

/** `t` for git keys in the current locale (reactive). */
export function useGitText() {
  const i18n = useI18n()
  return (key: GitKey, params?: I18nParams) => gitText(i18n.locale(), key, params)
}
