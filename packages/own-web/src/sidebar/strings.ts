const catalogs: Record<Locale, Partial<Record<SidebarKey, string>>> = { ko: sidebarKo, en: sidebarEn }

/** Same rules as `translate` in src/i18n: current locale, Korean fallback, `{name}` params, Korean particles. */
export function sidebarText(locale: Locale, key: SidebarKey, params?: I18nParams) {
  const template = catalogs[locale][key] ?? sidebarKo[key]
  const filled = params
    ? template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name]
        return value === undefined ? match : String(value)
      })
    : template
  return locale === "ko" ? applyJosa(filled) : filled
}

export type SidebarText = (key: SidebarKey, params?: I18nParams) => string

export function useSidebarText(): SidebarText {
  const i18n = useI18n()
  return (key, params) => sidebarText(i18n.locale(), key, params)
}
