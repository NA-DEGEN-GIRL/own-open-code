const catalogs: Record<Locale, Partial<Record<RequestsKey, string>>> = { ko: requestsKo, en: requestsEn }

/** Same rules as `translate` in src/i18n: current locale, Korean fallback, `{name}` params, Korean particles. */
export function requestsText(locale: Locale, key: RequestsKey, params?: I18nParams) {
  const template = catalogs[locale][key] ?? requestsKo[key]
  const filled = params
    ? template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name]
        return value === undefined ? match : String(value)
      })
    : template
  return locale === "ko" ? applyJosa(filled) : filled
}

export type RequestsText = (key: RequestsKey, params?: I18nParams) => string

export function useRequestsText(): RequestsText {
  const i18n = useI18n()
  return (key, params) => requestsText(i18n.locale(), key, params)
}
