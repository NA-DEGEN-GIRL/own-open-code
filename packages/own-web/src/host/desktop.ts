/** Same tag (session + kind) within this window: one OS notification (03 §9, 05 §7.4). */
export const NOTIFY_MERGE_MS = 10_000

/**
 * Longest notification tag handed to Windows unchanged. Electron uses `n#<origin>#<tag>` as the toast's tag, and a
 * Windows toast tag holds at most 64 characters: a longer one is neither shown nor reported (no show, no error; seen
 * in the packaged shell with `own:approval:local:<session id>`, 49 characters). 32 leaves room for any origin up to
 * 29 characters (`oc://renderer` is 13).
 */
export const TOAST_TAG_MAX = 32

/** The tag the OS sees: short tags as they are, longer ones as a stable short hash (same tag → same toast). */
export function toastTag(tag: string) {
  if (tag.length <= TOAST_TAG_MAX) return tag
  // cyrb53: 53-bit string hash, plenty for one window's notification tags.
  let h1 = 0xdeadbeef
  let h2 = 0x41c6ce57
  for (let index = 0; index < tag.length; index++) {
    const code = tag.charCodeAt(index)
    h1 = Math.imul(h1 ^ code, 2654435761)
    h2 = Math.imul(h2 ^ code, 1597334677)
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909)
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909)
  return `own-${(4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36)}`
}

