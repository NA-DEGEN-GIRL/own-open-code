/** What capability detection and notifications read from the page; tests pass their own. */
export interface DesktopEnvironment {
  /** The window is frameless and Windows draws its buttons over the page (05 §7.1, `navigator.windowControlsOverlay`). */
  readonly windowControlsOverlay: boolean
  /** HTML5 Notification. Main grants `notifications` to the renderer origin only (windows/security.ts). */
  readonly Notification?: typeof Notification
  /** `(pointer: coarse)` (03 §4.2.2). */
  readonly coarsePointer: boolean
  readonly now: () => number
  /**
   * The page is visible and has keyboard focus. Main's `WindowGetFocused` (`BrowserWindow.isFocused()`) can report a
   * minimized window as focused on Windows (seen in the packaged shell: minimized, another app in front, `true`), so
   * a hidden or unfocused page counts as "not focused" whatever main says. Absent: only main decides.
   */
  readonly pageActive?: () => boolean
}

/**
 * Upstream gives the window a title bar overlay on Windows only (windows/early.ts). The API object exists in every
 * Chromium page, so presence alone is not enough; `visible` is false while fullscreen, so the platform decides.
 */
export function pageEnvironment(): DesktopEnvironment {
  const overlay = (navigator as Navigator & { windowControlsOverlay?: { readonly visible: boolean } })
    .windowControlsOverlay
  return {
    windowControlsOverlay: !!overlay && (overlay.visible || /\bWindows\b/.test(navigator.userAgent)),
    Notification: typeof Notification === "function" ? Notification : undefined,
    coarsePointer: typeof matchMedia === "function" && matchMedia("(pointer: coarse)").matches,
    now: Date.now,
    pageActive: () => document.visibilityState !== "hidden" && document.hasFocus(),
  }
}

/** 05 §6.2 desktop column, from what this window actually has. */
export function desktopCapabilities(
  own: OwnShellApi,
  electron: ElectronBridge | undefined,
  env: DesktopEnvironment,
): HostCapabilities {
  return {
    windowControlsOverlay: env.windowControlsOverlay,
    // FilesOpenDirectoryPicker, FilesOpenPath/FilesRevealPath (+ AppResolveAppPath), FilesReadClipboardImage,
    // FilesSaveFile and the Plugin* calls are part of the IPC contract T0-0 checked, so the shell has them.
    nativeDirectoryPicker: true,
    // preload `getPathForFile` (webUtils); a preload without it cannot give real paths.
    nativeFilePaths: typeof electron?.getPathForFile === "function",
    openInApp: true,
    clipboardImage: true,
    // FilesSaveFile carries text only (shared/ipc-rpc/files.ts); binary blobs are refused (saveFile → false).
    saveDialog: true,
    // Toasts carry the shell's AUMID (dev.own.opencode.desktop, set by main). Not `Notification.permission` here:
    // reading it is a synchronous permission check answered by main's JS (windows/security.ts, which always grants
    // `notifications` to the renderer), and at startup main is still evaluating its bundle, so the read held the
    // first render for ~100 ms (PF1). The permission is checked when a notification is sent (createNotify).
    osNotifications: env.Notification ? "native" : "none",
    // The `browser.pane` Ipc is in the contract T0-0 checked (rpcHash input), and a shell of that contract starts the
    // browser extension with its first window (own-desktop src/main/desktop.ts).
    browserPane: true,
    serviceControl: typeof own.service?.status === "function" && typeof own.service?.restart === "function",
    // Upstream opens extra windows from its (macOS) menu only; there is no IPC for it.
    multiWindow: false,
    // Upstream moved keep-screen-active into its pairing GUI extension, which own-desktop does not start.
    keepScreenAwake: false,
    touch: env.coarsePointer,
    offlineCatalog: false,
    // 08 §4.1: a shell with `window.own.remotePcs` (absent in shells built before it).
    remotePcs: typeof own.remotePcs?.list === "function",
    // 08 §4.3: a shell with `window.own.mobilePreview`.
    mobilePreview: typeof own.mobilePreview?.status === "function",
    // 05 §7.3: a shell with the tray and `window.own.app`.
    appQuit: typeof own.app?.quit === "function",
  }
}

