/** T0-0 alone, so tests and the entry can check without importing upstream code. */
export function checkShell<T extends Pick<OwnShellApi, "shell">>(own: T | undefined, expected = RPC_HASH): T {
  if (!own) throw new ShellMismatchError(undefined, expected)
  if (own.shell.rpcHash !== expected) throw new ShellMismatchError(own.shell.rpcHash, expected)
  return own
}

export async function createDesktopHost(
  options: { readonly loadIpc?: () => Promise<IpcClient>; readonly environment?: DesktopEnvironment } = {},
): Promise<OwnHost> {
  const scope = window as unknown as { own?: OwnShellApi; electron?: ElectronBridge }
  const own = checkShell(scope.own)
  markShellStart(own)
  const ipc = await (options.loadIpc ?? (() => import("../../../desktop/src/renderer/ipc-client")))()
  // The client listens now: ask the preload for main's MessagePort (own-desktop preload, OwnIpc.portRequest).
  window.postMessage(OwnIpc.portRequest, "*")
  return desktopHost(own, ipc, scope.electron, options.environment ?? pageEnvironment())
}

export function desktopHost(
  own: OwnShellApi,
  ipc: IpcClient,
  electron: ElectronBridge | undefined,
  env: DesktopEnvironment = pageEnvironment(),
): OwnHost {
  let readied = false
  const connect = (tag: "AppAwaitInitialization" | "AppReconnectService") => async (): Promise<HostConnection> => {
    const [ready, controlDir] = await Promise.all([
      ipc.invoke(tag).catch((error: unknown) => {
        throw new HostUnavailableError(describe(error))
      }),
      own.shell.controlDir.catch(() => undefined),
    ])
    t0(tag === "AppAwaitInitialization" ? "own:t0:connect" : "own:t0:reconnect")
    return { baseUrl: ready.url, auth: "injected", controlDir: controlDir || undefined }
  }
  const capabilities = desktopCapabilities(own, electron, env)
  const service: HostService | undefined = capabilities.serviceControl
    ? {
        status: () => own.service.status(),
        restart: (input) => own.service.restart({ force: input.force, claudeConfigDir: input.claudeConfigDir }),
      }
    : undefined
  return {
    kind: "desktop",
    capabilities,
    connect: connect("AppAwaitInitialization"),
    reconnect: connect("AppReconnectService"),
    ready() {
      if (readied) return
      readied = true
      void ipc
        .invoke("WindowThemeReady")
        .then(() => t0("own:t0:ready"))
        .catch(() => undefined)
    },
    setChrome(theme) {
      const scheme = theme.scheme
      void ipc
        .invoke("WindowSetTitlebar", { theme: scheme ? { mode: theme.mode, scheme } : { mode: theme.mode } })
        .catch(() => undefined)
      void ipc.invoke("AppSetBackgroundColor", { color: theme.background }).catch(() => undefined)
    },
    openExternal(url) {
      if (!/^(https?:|mailto:)/i.test(url)) return
      ipc.send("FilesOpenExternal", { url })
    },
    files: desktopFiles(ipc, electron),
    browser: browserPane(ipc, own.browser),
    service,
    window: desktopWindow(ipc, typeof own.zoom?.step === "function" ? own.zoom : undefined),
    notify: capabilities.osNotifications === "none" ? undefined : createNotify(ipc, env),
    // The shell's calls as they are: names and states only, the pin, routes and token stay in main.
    remotePcs: capabilities.remotePcs ? own.remotePcs : undefined,
    // The same for the preview: the pairing link goes in, only its state comes out.
    mobilePreview: capabilities.mobilePreview ? own.mobilePreview : undefined,
    // 05 §7.3: 완전 종료's dialog is the shell's; the page only asks for it.
    app: capabilities.appQuit ? own.app : undefined,
    explorer: desktopExplorer(ipc),
  }
}

function desktopWindow(ipc: IpcClient, zoom: OwnZoomApi | undefined): HostWindow {
  return {
    focus: () => void ipc.invoke("WindowSetFocus").catch(() => undefined),
    show: () => void ipc.invoke("WindowShow").catch(() => undefined),
    isFocused: () => document.hasFocus(),
    // 05 §7.9: main keeps one factor for every window and announces each change, Ctrl+wheel and other windows' too.
    // It also sizes the WCO band to the factor (the appearance substitute's updateTitlebar).
    zoom: zoom && {
      levels: ZOOM_LEVELS,
      get: () => zoom.get(),
      set: (factor) => (Number.isFinite(factor) && factor > 0 ? zoom.set(factor) : zoom.get()),
      step: (direction) => zoom.step(direction),
      onChange: (listener) => zoom.onChange(listener),
    },
  }
}

function desktopFiles(ipc: IpcClient, electron: ElectronBridge | undefined): HostFiles {
  // `where <name>` per open is slow; a resolved editor stays resolved for the window's life.
  const apps = new Map<string, Promise<string>>()
  const application = (app: string) => {
    // A full path (a user-chosen editor) is used as is; `where` cannot take one.
    if (/^([A-Za-z]:[\\/]|\\\\|\/)/.test(app)) return Promise.resolve(app)
    let found = apps.get(app)
    if (!found) {
      // Main runs `execFile(application, [path])` (files/index.ts openPath): on Windows `code` is code.cmd, which
      // execFile cannot start, so the name goes through AppResolveAppPath first (upstream renderer/platform/files.ts
      // does the same). Off Windows main returns the name unchanged.
      found = ipc.invoke("AppResolveAppPath", { appName: app }).then((resolved) => {
        if (!resolved) throw new Error(storedLocale() === "en" ? `App not found: ${app}` : `앱을 찾을 수 없어요: ${app}`)
        return resolved
      })
      found.catch(() => apps.delete(app))
      apps.set(app, found)
    }
    return found
  }
  return {
    async pickDirectory(options) {
      const picked = await ipc.invoke("FilesOpenDirectoryPicker", {
        options: { multiple: false, ...(options?.defaultPath ? { defaultPath: options.defaultPath } : {}) },
      })
      if (Array.isArray(picked)) return picked[0] ?? null
      return typeof picked === "string" ? picked : null
    },
    async pickFile(options) {
      const picked = await ipc.invoke("FilesOpenFilePicker", {
        options: { multiple: false, ...(options?.defaultPath ? { defaultPath: options.defaultPath } : {}) },
      })
      if (!picked) return null
      // Only the path is wanted: main keeps a picked file readable until its token is released.
      void ipc.invoke("FilesReleasePickedFiles", { token: picked.token }).catch(() => undefined)
      return picked.files[0]?.path ?? null
    },
    pathForFile(file) {
      try {
        return electron?.getPathForFile?.(file) || null
      } catch {
        return null
      }
    },
    async readClipboardImage() {
      const image = await ipc.invoke("FilesReadClipboardImage").catch(() => null)
      if (!image) return null
      const bytes = image.buffer as Uint8Array
      const copy = new Uint8Array(bytes.byteLength)
      copy.set(bytes)
      // main re-encodes with nativeImage.toPNG() (files/index.ts readClipboardImage).
      return new Blob([copy], { type: "image/png" })
    },
    async openPath(path, app) {
      const resolved = app ? await application(app) : undefined
      // Without an app main returns shell.openPath's error text ("" or null on success); with one it throws.
      const failure = await ipc
        .invoke("FilesOpenPath", resolved ? { path, application: resolved } : { path })
        .catch((error: unknown) => {
          throw new Error(describe(error))
        })
      if (failure) throw new Error(failure)
    },
    async revealPath(path) {
      if (!(await ipc.invoke("FilesRevealPath", { path }))) throw new Error(storedLocale() === "en" ? `No such file: ${path}` : `파일이 없어요: ${path}`)
    },
    async saveFile(input) {
      const type = input.data.type
      if (type && !/^text\/|^application\/(json|xml|x-ndjson)/.test(type)) return false
      return ipc.invoke("FilesSaveFile", { options: { defaultPath: input.name }, content: await input.data.text() })
    },
  }
}

/** own-desktop's `explorer` plugin Ipc (packages/own-desktop/src/explorer/ipc.ts), called by name like the pane's. */
export const EXPLORER_IPC = "explorer"

/** How long a call waits for main to start the plugin when it came first (main starts it with the first window). */
export const EXPLORER_AVAILABLE_MS = 3_000

/**
 * `탐색기에서 열기` / `탐색기에서 보기` (05 §7.10) through PluginCall, so `window.own` and its contract stay as they
 * are. Main decides everything: which folders are open, folder or file, the program and its arguments. A shell without
 * the plugin answers `unavailable`: a file or folder of this PC then goes through upstream's FilesRevealPath as before,
 * everything else says the desktop app is older than this screen.
 */
function desktopExplorer(ipc: IpcClient): HostExplorer {
  const waiting = new Set<() => void>()
  let listening = false
  // A shell that never started the plugin within one wait has none: later calls answer at once.
  let absent = false
  const invoke = (method: string, input?: unknown) =>
    ipc.invoke("PluginCall", input === undefined ? { ipc: EXPLORER_IPC, method } : { ipc: EXPLORER_IPC, method, input })
  // True once main provides the Ipc: at once, or when its PluginAvailable comes within the wait.
  const started = async () => {
    if (!listening) {
      listening = true
      ipc.listen("PluginAvailable", (value) => {
        if (value.ipc !== EXPLORER_IPC || !value.available) return
        absent = false
        for (const open of [...waiting]) open()
      })
    }
    const arrived = new Promise<boolean>((resolve) => {
      const open = () => {
        clearTimeout(timer)
        waiting.delete(open)
        resolve(true)
      }
      const timer = setTimeout(() => {
        waiting.delete(open)
        resolve(false)
      }, EXPLORER_AVAILABLE_MS)
      waiting.add(open)
    })
    const subscribed = await ipc.invoke("PluginSubscribe", { ipc: EXPLORER_IPC }).catch(() => undefined)
    if (subscribed?.available) for (const open of [...waiting]) open()
    return arrived
  }
  const call = (method: string, input?: unknown): Promise<unknown> =>
    invoke(method, input).catch(async (cause: unknown) => {
      if (!paneUnavailable(paneFailure(cause)) || absent) throw paneFailure(cause)
      absent = !(await started())
      if (absent) throw paneFailure(cause)
      return invoke(method, input).catch((again: unknown) => {
        throw paneFailure(again)
      })
    })
  const result = (value: unknown): ExplorerResult => {
    const answer = value as ExplorerResult | null
    if (answer && typeof answer === "object" && typeof answer.ok === "boolean") return answer
    return { ok: false, reason: "failed" }
  }
  const failed = (cause: unknown): ExplorerResult =>
    paneUnavailable(cause)
      ? { ok: false, reason: "unavailable" }
      : { ok: false, reason: "failed", detail: describe(cause) }
  const program = (value: unknown): ExplorerProgram => {
    const answer = value as ExplorerProgram | null
    if (answer && typeof answer === "object" && typeof answer.template === "string") return answer
    throw new Error("explorer.program")
  }
  return {
    reveal: (path) =>
      call("reveal", { path }).then(result, (cause: unknown) => {
        if (!paneUnavailable(cause)) return failed(cause)
        return ipc
          .invoke("FilesRevealPath", { path })
          .then((found): ExplorerResult => (found ? { ok: true } : { ok: false, reason: "missing" }), failed)
      }),
    launch: (input) => call("launch", { host: input.host, path: input.path }).then(result, failed),
    program: () => call("program").then(program),
    pickProgram: () => call("pick").then(program),
    setTemplate: (template) => call("template", { template }).then(program),
    clearProgram: () => call("clear").then(program),
  }
}

/** The browser pane's GUI-extension Ipc (packages/gui-plugins/src/browser/ipc.ts `BrowserPane`). */
export const PANE_IPC = "browser.pane"

/**
 * How long a registration waits for main's browser extension to provide its Ipc. Main starts the extension with the
 * first window (own-desktop src/main/desktop.ts `plugins.start`) and PluginSubscribe starts it at once (upstream
 * `demand`), so the wait only runs out when the extension failed to load: the registration then reads as suspended and
 * the next use (the session's route, the pane, a turn) tries again.
 */
export const PANE_AVAILABLE_MS = 15_000

/**
 * What main's `browser.pane` emits for a binding (ipc.ts `PaneEvent`): own-web's events plus the host's own. `page`
 * (favicon and zoom after a navigation, upstream v2.0.28) and `focused` (the page took keyboard focus, v2.2; own-web
 * hears that from the shell's view focus) stop here instead of reaching the connection as a state without a browser.
 * `shortcut` (v2.2, which replaced `address`): a page with focus hands the window an app or pane chord (Ctrl+T, Ctrl+W,
 * Ctrl+L, Ctrl+Tab, Ctrl+Shift+P, …) it kept from the page; it runs as if typed in own-web, where the shortcut registry
 * listens on the window, like the shell's view keys below.
 */
type PaneEvent =
  | BrowserPaneEvent
  | { readonly type: "embed"; readonly tabID: string; readonly embed: string }
  | { readonly type: "inspect" }
  | { readonly type: "page"; readonly tabID: string; readonly icon?: string; readonly zoom: number }
  | { readonly type: "focused"; readonly tabID: string }
  | {
      readonly type: "shortcut"
      readonly key: string
      readonly code: string
      readonly ctrl: boolean
      readonly meta: boolean
      readonly shift: boolean
      readonly alt: boolean
    }

/** One registration in the window's event routing. */
interface Binding {
  event(event: PaneEvent): void
  /** The Ipc went away (the extension stopped): main dropped every binding without an event. */
  gone(): void
}

/** Closing reasons after which main's inventory is empty, so it is not kept for a later registration. */
const CLOSING: ReadonlySet<string> = new Set([PANE_CLOSED.closed, PANE_CLOSED.replaced, PANE_CLOSED.unsupported])

/**
 * `host.browser.register` (03 §16.7 adapter table) over upstream's `browser` GUI extension, written after its own
 * renderer client (gui-extensions/src/browser/connection.ts `open`, model.ts): one binding per registration, events
 * filtered by binding, every call after `register` has resolved. What differs from the BrowserPane IPC own-web's pane
 * (src/browser) was written against is absorbed here:
 *  - main resolves the target's server id from this window's PluginConfigure list, so the endpoint goes there first
 *    (the local service: its url only; main adds Basic for that exact origin, extension/host.ts `server`);
 *  - main may still be starting the extension: the first registration subscribes (PluginSubscribe, which starts it)
 *    and waits for PluginAvailable;
 *  - every tab page is its own host embed: `embed` events map tab → embed, a layout goes to its tab's embed
 *    (PluginEmbed) and hides the one placed before, a restored tab without a page is loaded when the pane shows it
 *    (`load`), and a capture is the embed's (PluginCapture, a JPEG of the shown page);
 *  - what main reports by rejecting rather than by a closed-state event becomes one: "unavailable" (the extension is
 *    not running, or went away) → suspended with the last tabs, any other register failure → registration.closed
 *    (own-web retries with backoff); a closed binding's own rejection waits for main's event.
 * Downloads (05 §8.4) and the close guard (7.2) come from the shell's own `window.own.browser`, when it has one, and
 * so do the split panes' view focus and the pane chords typed in a view (03 §4.1.1, own-desktop own-browser.ts).
 */
function browserPane(ipc: IpcClient, shell: OwnShellApi["browser"]): BrowserPanePlatform {
  const bindings = new Map<string, Binding>()
  const endpoints = new Map<string, BrowserPaneEndpoint>()
  let configured: Promise<unknown> = Promise.resolve()
  let listening = false
  let available = false
  let waiting: { readonly promise: Promise<void>; readonly open: () => void } | undefined
  const returned = new Set<() => void>()
  // Every way the pane's Ipc is found there (the event, or PluginSubscribe's answer); listeners hear each return.
  const becameAvailable = () => {
    const was = available
    available = true
    waiting?.open()
    if (!was) for (const listener of [...returned]) listener()
  }

  const call = (method: string, input: unknown) =>
    ipc.invoke("PluginCall", { ipc: PANE_IPC, method, input }).catch((cause: unknown) => {
      throw paneFailure(cause)
    })

  // Window-wide: the IPC client keeps one listener list per event tag for the window's life.
  const listen = () => {
    if (listening) return
    listening = true
    ipc.listen("PluginEvent", (value) => {
      if (value.ipc !== PANE_IPC || value.name !== "event") return
      const data = value.data as { readonly binding?: unknown; readonly event?: { readonly type?: unknown } } | null
      if (typeof data?.binding !== "string" || typeof data.event?.type !== "string") return
      bindings.get(data.binding)?.event(data.event as PaneEvent)
    })
    ipc.listen("PluginAvailable", (value) => {
      if (value.ipc !== PANE_IPC) return
      if (value.available) return becameAvailable()
      available = false
      for (const binding of [...bindings.values()]) binding.gone()
    })
  }

  const whenAvailable = (): Promise<void> => {
    if (available) return Promise.resolve()
    if (waiting) return waiting.promise
    let open = () => {}
    const promise = new Promise<void>((resolve, reject) => {
      const timer = setTimeout(() => {
        if (waiting?.promise === promise) waiting = undefined
        reject(Object.assign(new Error("browser.pane.unavailable"), { code: "unavailable" }))
      }, PANE_AVAILABLE_MS)
      open = () => {
        clearTimeout(timer)
        if (waiting?.promise === promise) waiting = undefined
        resolve()
      }
    })
    waiting = { promise, open }
    void ipc
      .invoke("PluginSubscribe", { ipc: PANE_IPC })
      .then((result) => {
        if (result.available) becameAvailable()
      })
      .catch(() => undefined)
    return promise
  }

  // Every endpoint a target named so far, sent again whenever one changes: main keeps the window's last list.
  const configure = (target: BrowserPaneTarget) => {
    const known = endpoints.get(target.serverKey)
    if (known && sameEndpoint(known, target.endpoint)) return configured
    endpoints.set(target.serverKey, target.endpoint)
    const servers = [...endpoints].map(([id, endpoint]) => ({
      id,
      url: endpoint.url,
      ...(endpoint.username === undefined ? {} : { username: endpoint.username }),
      ...(endpoint.password === undefined ? {} : { password: endpoint.password }),
    }))
    configured = ipc.invoke("PluginConfigure", { servers }).catch(() => undefined)
    return configured
  }

  // 03 §4.1.1: a pane chord typed inside a native view comes back from the shell; it runs as if typed in the page
  // (the shortcut registry listens on the window).
  shell?.onViewKey?.((key) =>
    window.dispatchEvent(
      new KeyboardEvent("keydown", {
        code: key.code,
        key: key.code,
        ctrlKey: key.ctrl,
        altKey: key.alt,
        shiftKey: key.shift,
        bubbles: true,
        cancelable: true,
      }),
    ),
  )
  return {
    platform: "desktop",
    ...(shell
      ? {
          downloads: { subscribe: (listener) => shell.onDownload(listener), save: (id) => shell.saveDownload(id) },
          guardClose: (on) => shell.guardClose(on),
        }
      : {}),
    // 03 §4.1.1: which native view the user clicked into (shells before split panes leave it out).
    ...(shell?.onViewFocus ? { onViewFocus: shell.onViewFocus } : {}),
    onAvailable(listener) {
      listen()
      returned.add(listener)
      return () => returned.delete(listener)
    },
    register(target: BrowserPaneTarget, listener: (event: BrowserPaneEvent) => void): BrowserPaneRegistration {
      listen()
      const binding = crypto.randomUUID()
      // Tab → its page's embed, as main reported them to this registration. A state never prunes it: main reports a
      // new page's embed straight away and the inventory that lists the page later, through the server.
      const embeds = new Map<string, string>()
      const loading = new Set<string>()
      let closed = false
      let wanted: BrowserPaneLayout | undefined
      let placed: string | undefined
      let last: BrowserState | null = target.restore ?? null
      const emit = (event: BrowserPaneEvent) => {
        if (!closed) listener(event)
      }
      // The pane itself is not there (its extension stopped or never came up): `lost`, so the connection registers
      // again on its own once the pane is back (upstream connection `refresh`).
      const suspend = () => emit({ type: "state", state: last, error: PANE_CLOSED.suspended, lost: true })
      const ready = whenAvailable()
        .then(() => configure(target))
        .then(() =>
          call("register", {
            binding,
            server: target.serverKey,
            session: target.sessionID,
            ...(target.restore ? { restore: target.restore } : {}),
          }),
        )
      const hide = () => {
        if (placed) ipc.send("PluginEmbed", { id: placed })
        placed = undefined
      }
      const load = (tabID: string) => {
        if (loading.has(tabID)) return
        loading.add(tabID)
        void ready.then(() => call("load", { binding, tabID })).catch(() => loading.delete(tabID))
      }
      // The wanted layout on its tab's embed; the embed placed before hides when another one takes the surface.
      const apply = () => {
        if (closed) return
        const layout = wanted
        const embed = layout ? embeds.get(layout.tabID) : undefined
        if (placed !== embed) hide()
        if (!layout) return
        if (!embed) {
          // A restored tab has no page until the pane shows it (upstream `load`); its embed event lays it out.
          if (layout.visible) load(layout.tabID)
          return
        }
        placed = embed
        ipc.send("PluginEmbed", { id: embed, layout: embedLayout(layout) })
      }
      bindings.set(binding, {
        event(event) {
          if (closed) return
          if (event.type === "embed") {
            embeds.set(event.tabID, event.embed)
            loading.delete(event.tabID)
            if (wanted?.tabID === event.tabID) apply()
            return
          }
          if (event.type === "shortcut")
            return void window.dispatchEvent(
              new KeyboardEvent("keydown", {
                key: event.key,
                code: event.code,
                ctrlKey: event.ctrl,
                metaKey: event.meta,
                shiftKey: event.shift,
                altKey: event.alt,
                bubbles: true,
                cancelable: true,
              }),
            )
          if (event.type === "inspect" || event.type === "page" || event.type === "focused") return
          if (event.type === "state" && event.state && !CLOSING.has(event.error ?? "")) last = event.state
          emit(event)
        },
        // Main withdraws the Ipc before it disposes the pane, so the pane's own suspended event never arrives.
        gone: suspend,
      })
      void ready.catch((error: unknown) => {
        if (paneUnavailable(error)) return suspend()
        // Main closed a binding it took: its closed-state event decides (it may still be on its way).
        if (describe(error) === PANE_CLOSED.closed) return
        emit({ type: "state", state: null, error: PANE_CLOSED.closed })
      })
      return {
        setLayout(layout) {
          if (closed) return
          wanted = layout
          apply()
        },
        command: (command: BrowserPaneCommand) =>
          ready
            .then(() => call("command", { binding, command }))
            .then(
              () => undefined,
              (error: unknown) => {
                if (paneUnavailable(error)) suspend()
                throw error
              },
            ),
        capture(tabID) {
          const embed = embeds.get(tabID)
          if (closed || !embed) return Promise.resolve(null)
          return ipc.invoke("PluginCapture", { id: embed }).then((data) => {
            if (!data) return null
            const copy = new Uint8Array(data.byteLength)
            copy.set(data)
            return new Blob([copy], { type: "image/jpeg" })
          })
        },
        close() {
          if (closed) return
          hide()
          closed = true
          bindings.delete(binding)
          void ready.then(() => call("close", { binding })).catch(() => undefined)
        },
      }
    },
  }
}

function sameEndpoint(a: BrowserPaneEndpoint, b: BrowserPaneEndpoint) {
  return a.url === b.url && a.username === b.username && a.password === b.password
}

/** PluginEmbed's layout: the pane's, without the tab (window DIPs with the zoom applied; RGBA background). */
function embedLayout(layout: BrowserPaneLayout) {
  return {
    visible: layout.visible,
    ...(layout.bounds ? { bounds: layout.bounds } : {}),
    ...(layout.background ? { background: layout.background } : {}),
    ...(layout.radius === undefined ? {} : { radius: layout.radius }),
  }
}

/** Main's PluginCall failure `{code, message?}` as an Error that keeps the code (upstream renderer/plugins.ts). */
function paneFailure(cause: unknown) {
  if (!cause || typeof cause !== "object" || !("code" in cause) || typeof cause.code !== "string") return cause
  const message = "message" in cause && typeof cause.message === "string" ? cause.message : cause.code
  return Object.assign(new Error(message), { code: cause.code })
}

/** The extension is not running in main (PluginError "unavailable"), or never came up. */
function paneUnavailable(error: unknown) {
  return error instanceof Error && "code" in error && error.code === "unavailable"
}

/**
 * OS notification (03 §9, 05 §7.4): the renderer's HTML5 Notification, which Windows shows as a toast of the shell's
 * AUMID. Like upstream's renderer/platform/notifications.ts: skipped while this window has focus, silent, a click
 * shows and focuses the window. Unlike it, "has focus" also needs the page to be visible and focused (`pageActive`),
 * and long tags are shortened for Windows (`toastTag`). Unlike it: no icon URL (the toast shows the app's own icon, no request per
 * notification), and one notification per tag within NOTIFY_MERGE_MS. Tagged notifications are events (turn end,
 * approval); an untagged one is the user's own action (settings: 테스트 알림) and shows even while focused.
 */
function createNotify(ipc: IpcClient, env: DesktopEnvironment) {
  const shown = new Map<string, number>()
  return (input: HostNotification) => {
    const Toast = env.Notification
    if (!Toast || Toast.permission === "denied") return
    const tag = input.tag
    const at = env.now()
    if (tag !== undefined) {
      const last = shown.get(tag)
      if (last !== undefined && at - last < NOTIFY_MERGE_MS) return
      for (const [key, time] of shown) if (at - time >= NOTIFY_MERGE_MS) shown.delete(key)
      shown.set(tag, at)
    }
    // A hidden (minimized) or unfocused page is never "focused", even when main says so (`pageActive`).
    const focused =
      tag === undefined || (env.pageActive && !env.pageActive())
        ? Promise.resolve(false)
        : ipc.invoke("WindowGetFocused").catch(() => document.hasFocus())
    void focused.then((isFocused) => {
      if (isFocused) {
        // Nothing went out, so a later event of the same kind is not merged into it.
        if (tag !== undefined && shown.get(tag) === at) shown.delete(tag)
        return
      }
      try {
        const notification = new Toast(input.title, {
          body: input.body,
          tag: tag === undefined ? undefined : toastTag(tag),
          silent: true,
        })
        notification.onclick = () => {
          void ipc.invoke("WindowShow").catch(() => undefined)
          void ipc.invoke("WindowSetFocus").catch(() => undefined)
          input.onClick?.()
          notification.close()
        }
      } catch {}
    })
  }
}

/** Diagnostics for the shell smoke test and benches: T0 calls that completed (names only, no data, R11). */
function t0(name: "own:t0:connect" | "own:t0:reconnect" | "own:t0:ready") {
  if (typeof performance !== "undefined") performance.mark(name)
}

/**
 * T0-6: the shell's start is earlier than this page's time origin, and `performance.mark` rejects a negative
 * startTime, so the mark sits at 0 and carries the offset: PF1 from shell start = sessions-visible + detail.offsetMs.
 */
function markShellStart(own: OwnShellApi) {
  void own.shell.startedAt
    .then((startedAt) => {
      if (typeof performance === "undefined" || performance.getEntriesByName("own:shell-start", "mark").length) return
      performance.mark("own:shell-start", {
        startTime: Math.max(0, startedAt - performance.timeOrigin),
        detail: { startedAt, offsetMs: Math.max(0, performance.timeOrigin - startedAt) },
      })
    })
    .catch(() => undefined)
}

/**
 * The shell fails AppAwaitInitialization with its own message (e.g. "런처가 오류로 끝났어요(종료 코드 1)"); over the RPC
 * wire it arrives as the cause of a generic defect error.
 */
export function describe(error: unknown): string {
  const cause = error instanceof Error ? error.cause : undefined
  const inner = cause && typeof cause === "object" && "message" in cause ? String(cause.message) : undefined
  if (inner) return inner
  if (error instanceof Error) return error.message
  if (error && typeof error === "object" && "message" in error) return String(error.message)
  return String(error)
}
