const catalogs: Record<Locale, Partial<Record<BrowserKey, string>>> = { ko: browserKo, en: browserEn }

export function browserText(locale: Locale, key: BrowserKey, params?: I18nParams) {
  const template = catalogs[locale][key] ?? browserKo[key]
  const filled = params
    ? template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name]
        return value === undefined ? match : String(value)
      })
    : template
  return locale === "ko" ? applyJosa(filled) : filled
}

export function useBrowserText() {
  const i18n = useI18n()
  return (key: BrowserKey, params?: I18nParams) => browserText(i18n.locale(), key, params)
}
