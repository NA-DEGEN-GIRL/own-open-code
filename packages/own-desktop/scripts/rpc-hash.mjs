// rpcHash (05 §5.5): the shell <-> renderer IPC contract as one short hash. The shell (main + preload build
// constants), own-web (desktop host, T0-0) and the release manifest (`desktop.rpc_hash`) carry the same value, so a
// renderer built against another contract never calls the shell's IPC.
//
// Inputs (05 §16): packages/desktop/src/shared/{ipc-rpc.ts, ipc-rpc/*.ts, ipc-transport.ts, ipc-contract.ts,
// window-bootstrap.ts}, the browser pane's GUI-extension Ipc that own-web calls through ExtensionCall
// (packages/gui-plugins/src/browser/ipc.ts, 05 §8.1) and packages/own-desktop/src/preload/own-api.ts. Hash = first
// 16 hex chars of the sha256 of their LF-normalized contents concatenated in repo-relative path order. Pure: the input
// files decide the value.
//
//   node packages/own-desktop/scripts/rpc-hash.mjs            print the hash
//   node packages/own-desktop/scripts/rpc-hash.mjs --write    update src/shared/rpc-hash.ts (the committed constant)
//   node packages/own-desktop/scripts/rpc-hash.mjs --check    exit 1 when src/shared/rpc-hash.ts is stale
//
// 05 §4.4 places this module at own/scripts/rpc-hash.mjs, computed once by build-own.ps1 (env OWN_RPC_HASH). It lives
// in the package until that build step exists; the builds re-check the committed constant against it.
import { createHash } from "node:crypto"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const PACKAGE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const REPO = path.resolve(PACKAGE, "../..")
export const GENERATED = path.join(PACKAGE, "src", "shared", "rpc-hash.ts")

/** Repo-relative input paths (forward slashes), sorted. */
export function rpcHashInputs(repo = REPO) {
  const shared = "packages/desktop/src/shared"
  const rpc = readdirSync(path.join(repo, shared, "ipc-rpc"))
    .filter((name) => name.endsWith(".ts") && !name.endsWith(".test.ts"))
    .map((name) => `${shared}/ipc-rpc/${name}`)
  return [
    `${shared}/ipc-rpc.ts`,
    ...rpc,
    `${shared}/ipc-transport.ts`,
    `${shared}/ipc-contract.ts`,
    `${shared}/window-bootstrap.ts`,
    "packages/gui-plugins/src/browser/ipc.ts",
    "packages/own-desktop/src/preload/own-api.ts",
  ].sort()
}

/**
 * The hash of the current inputs. With `expect` (e.g. env OWN_RPC_HASH from build-own.ps1) it throws when the value
 * differs, so a build never stamps a hash computed from other sources than the one the release recorded.
 */
export function rpcHash(options = {}) {
  const repo = options.repo ?? REPO
  const hash = createHash("sha256")
  for (const file of rpcHashInputs(repo)) hash.update(readFileSync(path.join(repo, file), "utf8").replace(/\r\n?/g, "\n"))
  const value = hash.digest("hex").slice(0, 16)
  if (options.expect && options.expect !== value)
    throw new Error(`rpcHash mismatch: computed ${value}, expected ${options.expect} (OWN_RPC_HASH)`)
  return value
}

export function generatedSource(value) {
  return [
    "// Generated by packages/own-desktop/scripts/rpc-hash.mjs --write. Do not edit.",
    "// rpcHash of the shell <-> renderer IPC contract (05 §5.5). own-desktop stamps it into main and preload",
    "// (import.meta.env.OWN_RPC_HASH, re-checked at build time); own-web's desktop host compares it with",
    "// window.own.shell.rpcHash before any IPC (T0-0).",
    `export const RPC_HASH = "${value}"`,
    "",
  ].join("\n")
}

/** The value committed in src/shared/rpc-hash.ts, or undefined. */
export function committedRpcHash(file = GENERATED) {
  try {
    return readFileSync(file, "utf8").match(/RPC_HASH = "([0-9a-f]{16})"/)?.[1]
  } catch {
    return undefined
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const value = rpcHash({ expect: process.env.OWN_RPC_HASH || undefined })
  if (process.argv.includes("--write")) {
    writeFileSync(GENERATED, generatedSource(value))
    console.log(`${value} -> ${path.relative(REPO, GENERATED)}`)
  } else if (process.argv.includes("--check")) {
    const committed = committedRpcHash()
    if (committed !== value) {
      console.error(`src/shared/rpc-hash.ts is stale: ${committed ?? "missing"} != ${value}; run: bun run rpc-hash --write`)
      process.exit(1)
    }
    console.log(value)
  } else console.log(value)
}
